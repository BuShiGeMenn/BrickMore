#!/usr/bin/env python3
"""Rebuild the five-level LaTeX table from archived GitHub evaluation records."""
import csv
import hashlib
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
INPUT = ROOT / "data" / "level_inputs"
SYSTEMS = ("BrickMore", "BrickGPT", "BrickNet")
DISPLAY = {"BrickMore": "BrickForma", "BrickGPT": "BrickGPT", "BrickNet": "BrickNet"}
METRICS = ("pinv", "vqa", "pe", "siglip2")

def main():
    with (INPUT / "scores.csv").open(encoding="utf-8-sig", newline="") as handle:
        records = list(csv.DictReader(handle))
    primary = [r for r in records if r["primary"].lower() == "true"]
    prompts = []
    for name in ("prompts_A.json", "prompts_B.json"):
        prompts.extend(json.loads((INPUT / name).read_text(encoding="utf-8"))["prompts"])
    reference = json.loads((INPUT / "audit_summary.json").read_text(encoding="utf-8"))
    provenance = json.loads((INPUT / "provenance.json").read_text(encoding="utf-8"))
    assert len(records) == 462 and len(primary) == 342 and len(prompts) == 114
    prompt_map = {p["prompt_id"]: p for p in prompts}
    assert len(prompt_map) == 114
    for system in SYSTEMS:
        selected = [r for r in primary if r["system"] == system]
        assert len(selected) == 114
        assert len({r["prompt_id"] for r in selected}) == 114
    for row in primary:
        p = prompt_map[row["prompt_id"]]
        assert row["caption"] == p["prompt"]
        assert int(row["level"]) == p["level"]
        assert row["category"] == p["category"]

    levels, output_rows = [], []
    for level, expected_n in zip(range(1, 6), (21, 21, 23, 25, 24)):
        pp = [p for p in prompts if p["level"] == level]
        assert len(pp) == expected_n
        words = [len(p["prompt"].split()) for p in pp]
        mean_words = sum(words) / len(words)
        stats = []
        for system in SYSTEMS:
            rr = [r for r in primary if r["system"] == system and int(r["level"]) == level]
            assert len(rr) == expected_n
            means = {}
            for metric in METRICS:
                values = [float(r[metric]) for r in rr]
                assert all(math.isfinite(v) for v in values)
                means[metric] = sum(values) / len(values)
                assert math.isclose(means[metric],
                                    reference["by_level"][str(level)][system][metric],
                                    rel_tol=0, abs_tol=1e-12)
            stats.append({"system": DISPLAY[system], "source_system": system, "n": len(rr), **means})
            output_rows.append({
                "level": level, "n_per_system": len(rr), "mean_words": mean_words,
                "system": DISPLAY[system], "source_system": system,
                "pinv_percent": 100 * means["pinv"],
                **{m: means[m] for m in METRICS if m != "pinv"},
            })
        levels.append({"level": level, "n_per_system": expected_n, "mean_words": mean_words,
                       "min_words": min(words), "max_words": max(words), "systems": stats})

    result = {
        "provenance": provenance,
        "input_sha256": {p.name: hashlib.sha256(p.read_bytes()).hexdigest()
                         for p in sorted(INPUT.iterdir()) if p.is_file()},
        "scope": {"total_records": len(records), "primary_records": len(primary), "matched_prompts": 114},
        "aggregation": "Mean of per-model scores. Text-image scores already use the maximum of eight views.",
        "pinv_units": "fraction in JSON; percent in the LaTeX table and output CSV",
        "word_count": "Whitespace-delimited English words; hyphenated forms count as one.",
        "levels": levels,
    }
    (ROOT / "data" / "level_results.json").write_text(
        json.dumps(result, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    with (ROOT / "data" / "level_results.csv").open("w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(output_rows[0]))
        writer.writeheader()
        writer.writerows(output_rows)

    lines = [
        "% Generated by scripts/build_level_results.py; edit the input data and rebuild.",
        "% GitHub source commit: " + provenance["commit"],
        r"\begin{table*}[t]",
        r"\centering",
        r"\small",
        r"\setlength{\tabcolsep}{5pt}",
        r"\begin{tabular}{lrrlrrrr}",
        r"\toprule",
        r"Level & $n$ & Words & System & $P_{\mathrm{inv}}\downarrow$ & VQA$\uparrow$ & PE$\uparrow$ & SigLIP2$\uparrow$ \\",
        r"\midrule",
    ]
    for index, entry in enumerate(levels):
        stats = entry["systems"]
        for system_index, stat in enumerate(stats):
            cells = []
            for metric in METRICS:
                best = (min if metric == "pinv" else max)(s[metric] for s in stats)
                value = (f"{100 * stat[metric]:.2f}" + r"\%") if metric == "pinv" else f"{stat[metric]:.4f}"
                cells.append(r"\textbf{" + value + "}" if abs(stat[metric] - best) < 1e-12 else value)
            prefix = (f"L{entry['level']} & {entry['n_per_system']} & {entry['mean_words']:.1f} & "
                      if system_index == 0 else " & & & ")
            lines.append(prefix + stat["system"] + " & " + " & ".join(cells) + r" \\")
        if index < len(levels) - 1:
            lines.append(r"\midrule")
    lines.extend([
        r"\bottomrule",
        r"\end{tabular}",
        r"\caption{Comparison across five description levels on 114 matched prompts. $n$ is the number of prompts per system; Words is the mean English word count. $P_{\mathrm{inv}}$ is the mean per-model invalid-placement ratio, shown as a percentage. Bold marks the best mean within each level, including ties. Higher text--image scores and lower $P_{\mathrm{inv}}$ are better.}",
        r"\label{tab:level-results}",
        r"\end{table*}",
    ])
    (ROOT / "tables").mkdir(exist_ok=True)
    (ROOT / "tables" / "level_results.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("Recomputed 15 system-by-level rows from 342 primary records.")
    print("Every metric matches the archived by-level audit within 1e-12.")
    for entry in levels:
        print(f"L{entry['level']}: n={entry['n_per_system']}, mean words={entry['mean_words']:.1f}")

if __name__ == "__main__":
    main()
